"""Curated preprocessing fixture intended for cross-language parity checks.

The fixture is generated by Python and pinned by this package's tests. A
production Dart preprocessing port can consume the same rows as its parity
contract; that port is not part of Phase 1.
"""

from __future__ import annotations

import json
from pathlib import Path

from .io import write_jsonl
from .preprocessing import PREPROCESSING_VERSION, preprocess

#: (note, original). Notes are for a human reading the fixture; they never
#: affect the expected values.
GOLDEN_CASES: tuple[tuple[str, str], ...] = (
    ("plain command", "turn the lights on"),
    ("capitalisation and final period", "Turn the LED on."),
    ("extra whitespace and repeated punctuation", "  SWITCH   ON the lights!! "),
    ("apostrophe is dropped by the parser", "don't turn the lights on"),
    ("typographic apostrophe", "Don\u2019t turn the lights on."),
    ("percent symbol", "set brightness to 50%"),
    ("decimal value", "set brightness to 0.5 percent"),
    ("signed number", "set brightness to -5 percent"),
    ("effect id", "activate effect 5"),
    ("hyphenated product name", "LEDDMX-03 strip"),
    ("accented latin text", "caf\u00e9 lights"),
    ("full-width digits and percent", "\uff15\uff10\uff05 bright"),
    ("em dash between clauses", "make the lights blue \u2014 now"),
    ("wake word with greeting", "hey walsey turn the lights on"),
    ("multiple greetings", "okay ok hey walsey turn the lights on"),
    ("only one wake word is stripped", "walsey walsey turn the lights on"),
    ("wake word in the middle is kept", "turn walsey on"),
    ("comma terminated", "Set brightness to 50%."),
    ("thousands separator", "set brightness to 1,000 percent"),
    ("tabs and non-breaking space", "\tmake\nthe lights\u00a0red "),
    ("zero-width space", "turn\u200b the lights on"),
    ("punctuation only", "!!!"),
    ("bare wake word", "walsey"),
    ("emoji only", "\U0001f680\U0001f31f"),
    ("non-latin script", "\u0627\u0644\u0639\u0631\u0628\u064a\u0629"),
    ("range with hyphen", "set brightness to 5-10 percent"),
    ("decimal alone", "0.5"),
    ("negative alone", "-5"),
    ("three sentences", "Turn on the lights. Then make them red."),
    ("empty input", ""),
)


def build_golden_rows() -> list[dict[str, object]]:
    rows: list[dict[str, object]] = []
    for note, original in GOLDEN_CASES:
        processed = preprocess(original)
        rows.append(
            {
                "note": note,
                "original": original,
                "canonical": processed.canonical,
                "tokens": list(processed.tokens),
                "actionTokens": list(processed.action_tokens),
                "numbers": list(processed.numbers),
                "preprocessingVersion": PREPROCESSING_VERSION,
            }
        )
    return rows


def write_golden(path: Path) -> int:
    return write_jsonl(path, build_golden_rows())


def read_golden(path: Path) -> list[dict[str, object]]:
    rows: list[dict[str, object]] = []
    with path.open("r", encoding="utf-8") as handle:
        for line in handle:
            line = line.strip()
            if line:
                rows.append(json.loads(line))
    return rows
